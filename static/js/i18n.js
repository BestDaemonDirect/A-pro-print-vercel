// Get current language from cookie or default to 'ru'
function getCurrentLang() {
  const match = document.cookie.match(/(?:^|;\s*)language=([^;]*)/);
  return match ? match[1] : 'ru';
}

// Set language cookie
function setLanguage(lang) {
  document.cookie = `language=${lang};path=/;max-age=31536000`;
}

// Apply translations to the page
function applyLanguage(lang) {
  // Set current language display
  const langDisplay = document.getElementById('currentLangDisplay');
  if (langDisplay) {
    const langNames = { ru: 'RU', en: 'EN', kk: 'KZ' };
    langDisplay.textContent = langNames[lang] || 'RU';
  }
  
  // Apply translations to elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (i18n[lang] && i18n[lang][key]) {
      el.textContent = i18n[lang][key];
    }
  });
  
  // Apply translations to placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (i18n[lang] && i18n[lang][key]) {
      el.placeholder = i18n[lang][key];
    }
  });
  
  // Store current language
  window.currentLang = lang;
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', function() {
  const currentLang = getCurrentLang();
  applyLanguage(currentLang);
  
  // Setup language switcher
  const langCard = document.getElementById('langCard');
  const langMenu = document.getElementById('langMenu');
  
  if (langCard && langMenu) {
    langCard.addEventListener('click', function(e) {
      e.stopPropagation();
      langMenu.classList.toggle('active');
    });
    
    document.querySelectorAll('.lang-option').forEach(option => {
      option.addEventListener('click', function() {
        const lang = this.dataset.lang;
        setLanguage(lang);
        applyLanguage(lang);
        langMenu.classList.remove('active');
      });
    });
    
    // Close menu when clicking outside
    document.addEventListener('click', function(e) {
      if (!langCard.contains(e.target) && !langMenu.contains(e.target)) {
        langMenu.classList.remove('active');
      }
    });
  }
});